"""Export the surprises and impulse responses of BS2023_replication.ipynb for the website.

Runs the notebook's own code cells (same data, same seed, same wild bootstrap) and
writes ../../data/replications/bs2023.js, a plain script that assigns
window.BS2023, so the site can read it even when opened from disk.

Run from this folder:  python export_web.py
"""
import contextlib
import io
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "data" / "replications" / "bs2023.js"

nb = json.loads((HERE / "BS2023_replication.ipynb").read_text(encoding="utf-8"))
ns = {}
log = io.StringIO()
with contextlib.redirect_stdout(log):
    for cell in nb["cells"]:
        if cell["cell_type"] != "code":
            continue
        src = "".join(cell["source"]).replace("plt.show()", "plt.close('all')")
        exec(compile(src, "notebook", "exec"), ns)

import numpy as np  # noqa: E402

r = lambda a, d=4: np.round(np.asarray(a, float), d).tolist()
RAW, ORTH = "raw  z", "orth z⊥"
z_raw, z_orth = ns["z_raw"].dropna(), ns["z_orth"].dropna()
assert (z_raw.index == z_orth.index).all()


def spec(name):
    lo, hi = ns["bands"][name]
    return {"point": r(ns["point"][name].T), "lo90": r(lo.T), "hi90": r(hi.T),
            "F": round(float(ns["F"][name]), 2)}


t1 = ns["table1"](ns["fomc"][(ns["fomc"]["Date"] >= "1988-01-01") & (ns["fomc"]["Date"] <= "2019-12-31")])
raw, orth = ns["point"][RAW], ns["point"][ORTH]
res_index = ns["res_index"]
data = {
    "vars": ns["VARS"],
    "units": ns["UNITS"],
    "horizon": int(ns["H"]),
    "nrep": int(ns["NREP"]),
    # monthly instrument, 1988:2-2019:12 (pp); zero in months without an announcement
    "months": [str(p) for p in z_raw.index],
    "z_raw": r(z_raw.values), "z_orth": r(z_orth.values),
    "raw": spec(RAW), "orth": spec(ORTH),
}

summary = [
    f"fomc       {int(t1.nobs)} announcements, 1988-2019; R2 on six pre-announcement indicators {t1.rsquared:.3f}",
    f"orth       monthly R2 {ns['first'].rsquared:.3f}; variance of z removed {1 - z_orth.var() / z_raw.var():.1%}",
    f"var        VAR({ns['P']}) in IP, CPI, EBP, 2y yield; {len(res_index)} months, {res_index[0]} to {res_index[-1]}",
    f"proxy      first-stage F: raw {data['raw']['F']:.2f}, orthogonalized {data['orth']['F']:.2f}",
    f"bootstrap  {data['nrep']} wild-bootstrap replications per instrument, seed {ns['SEED']}",
    f"ip         trough {raw[:, 0].min():+.2f}% (raw) vs {orth[:, 0].min():+.2f}% (orthogonalized)",
]


def write(lines):
    data["terminal"] = lines
    header = ("/* Generated by replications/BS2023/export_web.py from BS2023_replication.ipynb.\n"
              "   Monthly monetary policy surprises (raw and orthogonalized) and the proxy-SVAR responses\n"
              "   to a shock that raises the 2-year yield by 25bp, months 0-48, with 90% wild-bootstrap bands.\n"
              "   `terminal` is this script's own printed output. */\n")
    OUT.write_text(header + "window.BS2023 = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n",
                   encoding="utf-8")


OUT.parent.mkdir(parents=True, exist_ok=True)
write(summary + ["wrote      data/replications/bs2023.js (00.0 KB)"])      # first pass, to measure the size
summary.append(f"wrote      data/replications/bs2023.js ({OUT.stat().st_size / 1024:.1f} KB)")
write(summary)
print("\n".join(summary))
