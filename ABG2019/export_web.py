"""Export the one-quarter-ahead predictive densities of ABG2019_replication.ipynb for the website.

Runs the notebook's own code: the cells that load the data, estimate the quantile
regressions, fit the skewed t every quarter and evaluate the densities (Sections 1, 2,
6, 7 and the first lines of 8; the bootstrap and the figures are skipped, they are not
needed here). Writes ../../data/replications/abg2019.js, a plain script that assigns
window.ABG2019, so the site can read it even when opened from disk.

Run from this folder:  python export_web.py
"""
import contextlib
import io
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "data" / "replications" / "abg2019.js"

nb = json.loads((HERE / "ABG2019_replication.ipynb").read_text(encoding="utf-8"))
code = [c for c in nb["cells"] if c["cell_type"] == "code"]
src = lambda c: "".join(c["source"])
needed = ["DATA_FILE =", "def target(", "def qreg(", "def dskt(", "def fit_rows("]
cells = [src(c) for c in code if any(k in src(c) for k in needed)]
dens = next(src(c) for c in code if "DENS = " in src(c))
cells.append(dens[:dens.index("\n\n")])                      # YY grid and DENS only
assert len(cells) == 6

ns = {"display": lambda *a, **k: None}
log = io.StringIO()
with contextlib.redirect_stdout(log):
    for s in cells:
        exec(compile(s.replace("plt.show()", "plt.close('all')"), "notebook", "exec"), ns)

import numpy as np  # noqa: E402

h = 1
YY, DENS, ST, YQ, Y = ns["YY"], ns["DENS"][h], ns["ST"][h], ns["YQ"][h], ns["Y"][h]
jq, B, TDATE = ns["jq"], ns["B"][h], ns["TDATE"][h]
sel = np.isin(np.round(YY, 4), np.round(np.arange(-15, 10.0001, 0.25), 4))   # 0.25 grid on [-15, 10]
quarters = [f"{d.year}Q{d.quarter}" for d in TDATE]
q05 = YQ[:, jq(.05)]
worst = int(q05.argmin())

data = {
    "h": h,
    "quarters": quarters,                                    # target quarter t+1
    "gdp": np.round(Y, 2).tolist(),                          # realised growth, % annualised
    "grid": np.round(YY[sel], 2).tolist(),
    "density": np.round(DENS[:, sel], 4).tolist(),           # skewed-t density, one row per quarter
    "q05": np.round(q05, 2).tolist(), "q50": np.round(YQ[:, jq(.5)], 2).tolist(),
    "q95": np.round(YQ[:, jq(.95)], 2).tolist(),
    "params": np.round(ST, 3).tolist(),                      # loc, scale, shape, df
}

summary = [
    f"data       {len(ns['gdp'])} quarters of GDP growth and the NFCI, {quarters[0][:4]}-{quarters[-1][:4]}",
    f"qreg       19 quantiles by linear programming; NFCI slope {B[jq(.05)][2]:+.2f} at Q05, {B[jq(.95)][2]:+.2f} at Q95",
    f"skewed t   {len(ST)} quarterly fits to Q05, Q25, Q75, Q95; median df {np.median(ST[:, 3]):.0f}",
    f"density    {sel.sum()} points on [-15, 10] per quarter, h = {h}",
    f"tail       lowest Q05 {q05[worst]:+.2f}% in {quarters[worst]}; median Q05 {np.median(q05):+.2f}%",
]


def write(lines):
    data["terminal"] = lines
    header = ("/* Generated by replications/ABG2019/export_web.py from ABG2019_replication.ipynb.\n"
              "   One-quarter-ahead predictive densities of GDP growth (skewed t fitted to the quantile\n"
              "   regressions on GDP and the NFCI), one per quarter, with realised growth and Q05/Q50/Q95.\n"
              "   `terminal` is this script's own printed output. */\n")
    OUT.write_text(header + "window.ABG2019 = " + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")


OUT.parent.mkdir(parents=True, exist_ok=True)
write(summary + ["wrote      data/replications/abg2019.js (000.0 KB)"])      # first pass, to measure the size
summary.append(f"wrote      data/replications/abg2019.js ({OUT.stat().st_size / 1024:.1f} KB)")
write(summary)
print("\n".join(summary))
