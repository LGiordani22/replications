"""Export the impulse responses of CEE2005_replication.ipynb for the website.

Runs the notebook's own code cells (same data, same seed, same bootstrap) and
writes ../../data/replications/cee2005.js, a plain script that assigns
window.CEE2005, so the site can read it even when opened from disk.

Run from this folder:  python export_web.py
"""
import contextlib
import io
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "data" / "replications" / "cee2005.js"

nb = json.loads((HERE / "CEE2005_replication.ipynb").read_text(encoding="utf-8"))
ns = {}
log = io.StringIO()
with contextlib.redirect_stdout(log):
    for cell in nb["cells"]:
        if cell["cell_type"] != "code":
            continue
        src = "".join(cell["source"]).replace("plt.show()", "plt.close('all')")
        exec(compile(src, "notebook", "exec"), ns)

import numpy as np  # noqa: E402

VARS, VARS_c = ns["VARS"], ns["VARS_c"]
r = lambda a: np.round(np.asarray(a, float), 4).tolist()


def spec(point, draws, names):
    lo95, lo68, hi68, hi95 = np.percentile(draws, [2.5, 16, 84, 97.5], axis=0)
    idx = [names.index(v) for v in VARS]
    return {"point": r(point[idx]), "lo68": r(lo68[idx]), "hi68": r(hi68[idx]),
            "lo95": r(lo95[idx]), "hi95": r(hi95[idx])}


point, draws = ns["point"], ns["draws"]
D = VARS.index("Deflator")
data = {
    "vars": VARS,
    "units": ns["UNITS"],
    "horizon": int(ns["H"]),
    "nrep": int(ns["NREP"]),
    "baseline": spec(point, draws, VARS),
    "commodity": spec(ns["point_c"], ns["draws_c"], VARS_c),
    # facts quoted in the terminal, read from the same objects the notebook prints
    "facts": {
        "quarters": int(len(ns["data"]) - ns["P"]),
        "start": str(ns["data"].index[ns["P"]]), "end": str(ns["data"].index[-1]),
        "max_root": round(float(ns["roots"].max()), 4),
        "impact": {v: round(float(point[VARS.index(v), 0]), 3) for v in ["Fed funds", "Real profits", "M2 growth"]},
        "gdp_peak": round(float(point[0].max()), 2), "gdp_peak_q": int(point[0].argmax()),
        "deflator_trough": round(float(point[D].min()), 2), "deflator_trough_q": int(point[D].argmin()),
        "deflator_trough_commodity": round(float(ns["point_c"][VARS_c.index("Deflator")].min()), 2),
    },
}

f = data["facts"]
imp = f["impact"]
summary = [
    f"data       {f['quarters']} quarters, {f['start']} to {f['end']} (+4 pre-sample)",
    f"var        VAR(4), 9 variables, OLS; largest root {f['max_root']}",
    "identify   Cholesky, shock = fed funds (7th of 9)",
    f"impact     fed funds {imp['Fed funds']:+.3f} pp   profits {imp['Real profits']:+.3f}%   M2 growth {imp['M2 growth']:+.3f} pp",
    f"bootstrap  {data['nrep']} replications, residuals rescaled by sqrt(T/(T-k)), seed 1234",
    f"gdp        peak {f['gdp_peak']:+.2f}% at quarter {f['gdp_peak_q']}",
    f"deflator   trough {f['deflator_trough']:+.2f}% at quarter {f['deflator_trough_q']}; "
    f"{f['deflator_trough_commodity']:+.2f}% with commodity prices",
]


def write(lines):
    data["terminal"] = lines
    header = ("/* Generated by replications/CEE2005/export_web.py from CEE2005_replication.ipynb.\n"
              "   Impulse responses to an expansionary monetary policy shock (one s.d. fall in the\n"
              "   federal funds rate), quarters 0-20, with 68% and 95% residual-bootstrap bands.\n"
              "   `terminal` is this script's own printed output. */\n")
    OUT.write_text(header + "window.CEE2005 = " + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")


OUT.parent.mkdir(parents=True, exist_ok=True)
write(summary + ["wrote      data/replications/cee2005.js (00.0 KB)"])      # first pass, to measure the size
summary.append(f"wrote      data/replications/cee2005.js ({OUT.stat().st_size / 1024:.1f} KB)")
write(summary)
print("\n".join(summary))
